export type GlyphName = keyof typeof GLYPHS;

/**
 * The SVG attributes of one path, however the table stored it — a bare string or
 * an entry carrying its own transform and opacity.
 */
function pathAttributes(entry: GlyphPath): {
  d: string;
  transform?: string;
  opacity?: number;
  stroke?: boolean;
} {
  if (typeof entry === "string") return { d: entry };
  const attributes: {
    d: string;
    transform?: string;
    opacity?: number;
    stroke?: boolean;
  } = { d: entry.d };
  if (entry.transform !== undefined) attributes.transform = entry.transform;
  if (entry.opacity !== undefined) attributes.opacity = entry.opacity;
  if (entry.stroke !== undefined) attributes.stroke = entry.stroke;
  return attributes;
}

/**
 * One glyph at its natural size. dsh renders every row glyph at 14 inside a 16px
 * box, so 14 is the default here too.
 */
export function Glyph({
  name,
  size = 14,
  ...props
}: { name: GlyphName; size?: number } & SVGProps<SVGSVGElement>) {
  const glyph = GLYPHS[name];
  // Most of dsh's set is a filled path. A few, like the database outline used
  // for the models nav item, are stroked instead — filling one would close the
  // outline into a solid blob, so the two modes are explicit per glyph rather
  // than inferred from the name.
  const glyphStrokeWidth = "strokeWidth" in glyph ? (glyph.strokeWidth as number) : null;
  const strokeLinejoin = "strokeLinejoin" in glyph ? glyph.strokeLinejoin : undefined;
  const circles = "circles" in glyph ? (glyph.circles ?? []) : [];
  const evenOdd = "evenOdd" in glyph && glyph.evenOdd === true;
  return (
    <svg
      width={size}
      height={size}
      viewBox={glyph.viewBox}
      fill="none"
      aria-hidden
      // The glyph's own name, so a test can name the mark it expects instead of
      // matching path data it should never have to know about.
      data-glyph={name}
      {...props}
    >
      {glyph.paths.map((entry, index) => {
        const { d, transform, opacity, stroke } = pathAttributes(entry);
        // A path is stroked when it says so; failing that it follows its glyph,
        // which is stroked when it declares a width. That is what lets dsh's
        // half-and-half glyphs (an outlined box with a filled lid, a filled
        // plus with a stroked folder) come out as drawn instead of as one mode
        // applied to both halves.
        const stroked = stroke ?? glyphStrokeWidth !== null;
        return stroked ? (
          <path
            key={index}
            d={d}
            transform={transform}
            opacity={opacity}
            fill="none"
            stroke="currentColor"
            strokeWidth={glyphStrokeWidth ?? 1}
            strokeLinecap="round"
            strokeLinejoin={strokeLinejoin}
          />
        ) : (
          <path
            key={index}
            d={d}
            transform={transform}
            opacity={opacity}
            fill="currentColor"
            fillRule={evenOdd ? "evenodd" : undefined}
          />
        );
      })}
      {circles.map((circle, index) => (
        <circle
          key={`circle-${String(index)}`}
          cx={circle.cx}
          cy={circle.cy}
          r={circle.r}
          fill="none"
          stroke="currentColor"
          strokeWidth={glyphStrokeWidth ?? 1}
        />
      ))}
    </svg>
  );
}
